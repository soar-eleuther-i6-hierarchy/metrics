# Guards that a metrics report must record before it may be used. A report written
# before BOS exclusion landed carries neither, and its numbers are not comparable with
# anything written after: BOS is an attention sink, so with 400 documents every feature
# pair in the dictionary collected 400 joint firings from that one position and cleared
# MIN_JOINT on its own. Such a file was used as the Matryoshka baseline for a day and
# inflated the T-SAE edge-density ratio from 794x to 1,760x. See
# outputs/gemma-2-2b/layer_12/withdrawn/README.md and ERROR_LOG 2026-09-11.
#
# The check is on absence, not value: these keys entered the config block together with
# the guards they name, so a report that omits one predates it.
_REQUIRED_CONFIG = ("bos_excluded", "min_joint")


def read(path: Path, *, require_guards: bool = True):
    """Load a JSON result, refusing a metrics report that predates the current guards.

    `require_guards` is on by default and should stay on for anything that becomes a
    number in the paper. Pass False only to inspect an old file deliberately.
    """
    if not path.is_file():
        return None
    d = json.loads(path.read_text())
    cfg = d.get("config")
    if require_guards and isinstance(cfg, dict) and "block_ranges" in cfg:
        missing = [k for k in _REQUIRED_CONFIG if k not in cfg]
        if missing:
            raise ValueError(
                f"{path} is a metrics report whose config omits {missing}, so it was "
                f"graded before those guards existed and cannot be compared with a "
                f"current report. It records {d.get('total_tokens')} tokens; current "
                f"gemma runs record 48,571. See "
                f"outputs/gemma-2-2b/layer_12/withdrawn/README.md."
            )
    return d


def ms(vals, p=3, pm=True):
    """mean, and the spread over seeds. One run has no spread and must not pretend to."""
    v = [x for x in vals if x is not None]
    if not v:
        return "--"
    if len(v) == 1 or not pm:
        return f"{st.mean(v):.{p}f}"
    return rf"{st.mean(v):.{p}f}\,$\pm$\,{st.pstdev(v):.{p}f}"


def esc(t) -> str:
    s = str(t)
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"),
                 ("&", r"\&"), ("#", r"\#")):
        s = s.replace(a, b)
    return s


def table(label, caption, header, rows, align=None, note=None, size="small"):
    r"""One booktabs table, caption above the rules, matching make_report_tables.table."""
    align = align or ("l" + "r" * (len(header) - 1))
    L = [r"\begin{table}[tbp]", r"  \centering", rf"  \{size}",
         rf"  \caption{{{caption}}}", rf"  \label{{tab:{label}}}",
         rf"  \begin{{tabular}}{{{align}}}", r"    \toprule",
         "    " + " & ".join(header) + r" \\", r"    \midrule"]
    L += ["    " + (r if isinstance(r, str)
                    else " & ".join(str(c) for c in r) + r" \\") for r in rows]
    L += [r"    \bottomrule", r"  \end{tabular}"]
    if note:
        L.append(rf"  \\[2pt] \footnotesize {note}")
    L.append(r"\end{table}")
    return "\n".join(L)


def figure(label, caption, path, width=r"\linewidth", note=None):
    L = [r"\begin{figure}[tbp]", r"  \centering",
         rf"  \includegraphics[width={width}]{{{path}}}",
         rf"  \caption{{{caption}}}", rf"  \label{{fig:{label}}}"]
    if note:
        L.append(rf"  \\[2pt] \footnotesize {note}")
    L.append(r"\end{figure}")
    return "\n".join(L)


def emit(out_dir: Path, filename: str, gen: str, parts) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    L = [HEAD.format(gen=gen)]
    for slot, section, tex in parts:
        if section:
            L += ["", "% " + "-" * 72, f"% {section}", "% " + "-" * 72]
        L += ["", f"% [{slot}]", tex]
    dest = out_dir / filename
    dest.write_text("\n".join(L) + "\n")
    return dest


