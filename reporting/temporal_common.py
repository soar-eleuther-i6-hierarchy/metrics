"""Shared helpers for the Temporal SAE and Priors-in-Time report generators.

Both read the frozen run results rather than the prose written about them: `toy-temporal/`
for the toy runs, and `gemma-2-2b-tsae/`, `gemma-2-2b-pit/` and `gemma-2-2b/` for the released
checkpoints. A generator that read a findings file would make the paper agree with our summary
rather than with the run.

Captions are emitted as `TODO(caption)` on purpose. A caption states what a reader should take
from a figure, and that is a judgement for a person, not a format string.
"""
